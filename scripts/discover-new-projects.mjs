#!/usr/bin/env node
/**
 * discover-new-projects.mjs — weekly GitHub Search for new candidates.
 *
 * Runs a handful of GitHub Search queries covering the four content
 * pillars (mcp / agent / skill / network).  Anything with > 200 stars
 * AND not already in lib/github-projects.ts is written to
 * scripts/discover-new-projects.md as a "review queue".  It is
 * intentionally NOT auto-merged — adding an entry still needs a
 * human to fill in `area` / `descriptionCn` / `whyCn` / `installCommand`
 * because those are editorial choices.
 *
 * Usage:
 *   GITHUB_PERSONAL_ACCESS_TOKEN=... node scripts/discover-new-projects.mjs
 *
 * Output:
 *   scripts/discover-new-projects.md  (truncated/overwritten each run)
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const OUT = join(ROOT, "scripts", "discover-new-projects.md");

const TOKEN = process.env.GITHUB_PERSONAL_ACCESS_TOKEN || process.env.GITHUB_TOKEN;
const HEADERS = {
  "accept": "application/vnd.github+json",
  "x-github-api-version": "2022-11-28",
  "user-agent": "security-toolbox-weekly-refresh",
  ...(TOKEN ? { "authorization": `Bearer ${TOKEN}` } : {}),
};
const STARS_MIN = Number(process.env.DISCOVER_STARS_MIN || 200);
const PER_QUERY = 20;

const QUERIES = [
  { pillar: "MCP",   q: "mcp-server security stars:>200" },
  { pillar: "Agent", q: "topic:ai-agents security stars:>200" },
  { pillar: "Skill", q: "topic:claude-skills stars:>200" },
  { pillar: "Skill", q: "topic:prompt-skills stars:>200" },
];

const { readFile } = await import("node:fs/promises");
const src = await readFile(join(ROOT, "lib", "github-projects.ts"), "utf8");
/* Match either the slug field or the `owner/repo` literal so a
 * candidate like `0x4m4/hexstrike-ai` is correctly recognised as
 * "already in repo" when the entry's slug is just `hexstrike-ai`. */
const knownSlugs = new Set([
  ...[...src.matchAll(/slug:\s*"([^"]+)"/g)].map((m) => m[1]),
  ...[...src.matchAll(/owner:\s*"([^"]+)"[^{}]*?repo:\s*"([^"]+)"/g)]
    .map((m) => `${m[1]}/${m[2]}`.toLowerCase()),
]);

async function search(q) {
  const url = `https://api.github.com/search/repositories?per_page=${PER_QUERY}&sort=stars&order=desc&q=${encodeURIComponent(q)}`;
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), 15_000);
  try {
    const res = await fetch(url, { headers: HEADERS, signal: ac.signal });
    if (!res.ok) {
      return { ok: false, status: res.status, total: 0, items: [] };
    }
    const data = await res.json();
    return { ok: true, total: data.total_count || 0, items: data.items || [] };
  } catch (e) {
    return { ok: false, err: String(e), total: 0, items: [] };
  } finally {
    clearTimeout(t);
  }
}

const lines = [];
lines.push(`# New project candidates (auto-discovered, NOT auto-merged)`);
lines.push("");
lines.push(`> Generated by scripts/discover-new-projects.mjs`);
lines.push(`> Threshold: stars > ${STARS_MIN} · Existing slugs excluded.`);
lines.push(`> Pick the ones that match a real SecToolbox category, fill in `);
lines.push(`> the editorial fields (area, descriptionCn, whyCn, installCommand),`);
lines.push(`> and paste into lib/github-projects.ts.`);
lines.push("");

let totalNew = 0;
for (const { pillar, q } of QUERIES) {
  lines.push(`## ${pillar}: \`${q}\``);
  lines.push("");
  const r = await search(q);
  if (!r.ok) {
    const reason = r.status ? `${r.status}` : r.err;
    lines.push(`_search failed: ${reason} — quota or transient. Will retry next week._`);
    lines.push("");
    continue;
  }
  lines.push(`Total matches on GitHub: **${r.total.toLocaleString()}** (showing top ${PER_QUERY} by stars)`);
  lines.push("");
  lines.push("| Repo | Stars | Lang | Description | Already in repo? |");
  lines.push("|---|---:|---|---|:-:|");
  for (const it of r.items) {
    const slug = it.full_name.toLowerCase().replace(/[/.]/g, "-");
    const fullName = it.full_name.toLowerCase();
    const inRepo = (knownSlugs.has(slug) || knownSlugs.has(fullName)) ? "✓" : "🆕";
    if (inRepo === "🆕") totalNew++;
    const desc = (it.description || "").replace(/\|/g, "\\|").slice(0, 120);
    lines.push(`| [${it.full_name}](${it.html_url}) | ${it.stargazers_count.toLocaleString()} | ${it.language || "—"} | ${desc} | ${inRepo} |`);
  }
  lines.push("");
}

lines.push("---");
lines.push("");
lines.push(`**${totalNew} new candidates** found across all queries.`);
lines.push("");

await writeFile(OUT, lines.join("\n"), "utf8");
console.log(`Wrote ${OUT} (${totalNew} new candidates)`);
